// Raw events before ImGui: the capture, closing, and what the host must see later.
bool menu_event(Menu &m, const SDL_Event &ev)
{
    switch (ev.type) {
    case SDL_QUIT:
        m.quit = true;
        return true;
    case SDL_WINDOWEVENT:
        if (ev.window.event == SDL_WINDOWEVENT_SIZE_CHANGED) m.for_host.push_back(ev);
        return false;
    case SDL_CONTROLLERDEVICEADDED:
    case SDL_CONTROLLERDEVICEREMOVED:
        m.for_host.push_back(ev);
        return false;
    default:
        break;
    }
    if (m.capture_row >= 0) {
        bool done = false;
        if (ev.type == SDL_KEYDOWN && !ev.key.repeat) {
            SDL_Scancode sc = ev.key.keysym.scancode;
            if (sc == SDL_SCANCODE_DELETE || sc == SDL_SCANCODE_BACKSPACE) app_bind_set(m.capture_row, m.capture_pad, 0);
            else if (sc != SDL_SCANCODE_ESCAPE && !m.capture_pad) say(m, app_bind_set(m.capture_row, false, sc));
            done = sc == SDL_SCANCODE_ESCAPE || sc == SDL_SCANCODE_DELETE || sc == SDL_SCANCODE_BACKSPACE || !m.capture_pad;
        } else if (ev.type == SDL_CONTROLLERBUTTONDOWN) {
            if (m.capture_pad) say(m, app_bind_set(m.capture_row, true, 1 + ev.cbutton.button));
            done = m.capture_pad || ev.cbutton.button == SDL_CONTROLLER_BUTTON_B;
        } else if (m.capture_pad && ev.type == SDL_CONTROLLERAXISMOTION && (ev.caxis.value > 20000 || ev.caxis.value < -20000)) {
            say(m, app_bind_set(m.capture_row, true, 100 + ev.caxis.axis * 2 + (ev.caxis.value > 0 ? 1 : 0)));
            done = true;
        } else if (ev.type == SDL_MOUSEBUTTONDOWN) {
            done = true;
        }
        if (done) {
            m.capture_row = -1;
            m.hold = true;
        }
        return ev.type == SDL_KEYDOWN || ev.type == SDL_KEYUP || ev.type == SDL_CONTROLLERBUTTONDOWN ||
               ev.type == SDL_CONTROLLERBUTTONUP || ev.type == SDL_CONTROLLERAXISMOTION || ev.type == SDL_MOUSEBUTTONDOWN;
    }
    if (ev.type == SDL_KEYDOWN && !ev.key.repeat) {
        const SDL_Scancode sc = ev.key.keysym.scancode;
        if (sc != SDL_SCANCODE_ESCAPE && app_is_menu_key(sc)) { m.resume = true; return true; }
        if (sc == SDL_SCANCODE_ESCAPE && !m.busy) { m.resume = true; return true; }
    }
    if (ev.type == SDL_CONTROLLERBUTTONDOWN) {
        if (app_is_menu_button(ev.cbutton.button)) { m.resume = true; return true; }
        if (ev.cbutton.button == SDL_CONTROLLER_BUTTON_B && !m.busy) { m.resume = true; return true; }
    }
    return false;
}

// DUCKTALES_UI_SELFTEST=<dir> (QA only): the menu walks its tabs and
// categories and the first-run screen shows its states by themselves, each
// written to <dir> as a PNG of what the window draws, so a hidden window can
// still be looked at. Steps with a size draw off screen at that size.
const char *selftest_dir()
{
    const char *d = std::getenv("DUCKTALES_UI_SELFTEST");
    return d && *d ? d : nullptr;
}

void selftest_shot(SDL_Renderer *ren, int ow, int oh, const char *name)
{
    std::vector<uint32_t> px((size_t)ow * (size_t)oh);
    std::string path = std::string(selftest_dir()) + "/" + name + ".png";
    bool ok = ow > 0 && SDL_RenderReadPixels(ren, nullptr, SDL_PIXELFORMAT_ARGB8888, px.data(), ow * 4) == 0 &&
              cyc_write_png(path.c_str(), px.data(), ow, oh);
    std::printf("[selftest] %s %s (%dx%d)\n", ok ? "wrote" : "could not write", path.c_str(), ow, oh);
    std::fflush(stdout);
}

// Where the window draws the picture: 1:1 when it is already at drawable
// resolution, otherwise fitted (whole multiples with integer scaling).
void draw_picture(SDL_Renderer *ren, SDL_Texture *tex, int pw, int ph, bool exact, int ow, int oh)
{
    if (!tex || pw <= 0 || ph <= 0) return;
    AppDisplay d;
    app_display_get(&d);
    float s = (float)ow / pw < (float)oh / ph ? (float)ow / pw : (float)oh / ph;
    if (exact && pw <= ow && ph <= oh) s = 1.0f;
    else if (d.integer_scale && s >= 1.0f) s = (float)(int)s;
    SDL_Rect dst = { (int)((ow - pw * s) / 2), (int)((oh - ph * s) / 2), (int)(pw * s), (int)(ph * s) };
    SDL_RenderCopy(ren, tex, nullptr, &dst);
}

