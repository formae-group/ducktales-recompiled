struct Imgui {
    SDL_Window *win = nullptr;
    SDL_Renderer *ren = nullptr;
    ImGuiContext *ctx = nullptr;
    Fonts fonts;
    bool begin(SDL_Window *w, SDL_Renderer *r)
    {
        win = w;
        ren = r;
        IMGUI_CHECKVERSION();
        ctx = ImGui::CreateContext();
        ImGui::SetCurrentContext(ctx);
        ImGuiIO &io = ImGui::GetIO();
        io.IniFilename = nullptr;
        io.LogFilename = nullptr;
        io.ConfigFlags |= ImGuiConfigFlags_NavEnableKeyboard | ImGuiConfigFlags_NavEnableGamepad;
        if (!ImGui_ImplSDL2_InitForSDLRenderer(w, r)) { ImGui::DestroyContext(ctx); ctx = nullptr; return false; }
        if (!ImGui_ImplSDLRenderer2_Init(r)) { ImGui_ImplSDL2_Shutdown(); ImGui::DestroyContext(ctx); ctx = nullptr; return false; }
        int ow = 0, oh = 0;
        SDL_GetRendererOutputSize(r, &ow, &oh);
        fit(ui_base(w, oh));
        return true;
    }
    // Between frames: the fonts and the style for another base size.
    void fit(float base)
    {
        if (base == fonts.base) return;
        fonts = load_fonts(base);
        ImGui_ImplSDLRenderer2_DestroyFontsTexture();
        apply_style(base);
    }
    void end()
    {
        if (!ctx) return;
        ImGui::SetCurrentContext(ctx);
        ImGui_ImplSDLRenderer2_Shutdown();
        ImGui_ImplSDL2_Shutdown();
        ImGui::DestroyContext(ctx);
        ctx = nullptr;
    }
};

// The Formae logo (assets/brand/formae.png, embedded): its coverage, drawn
// in its own colour at the size asked for, area-averaged from the original.
struct Logo {
    std::vector<unsigned char> alpha;
    uint32_t rgb = 0;
    int sw = 0, sh = 0;
    SDL_Texture *tex = nullptr;
    int w = 0, h = 0;
    void load()
    {
        int n = 0;
        unsigned char *px = stbi_load_from_memory(app_about_logo_png, (int)app_about_logo_png_size, &sw, &sh, &n, 4);
        if (!px) { sw = sh = 0; return; }
        alpha.resize((size_t)sw * (size_t)sh);
        for (size_t i = 0; i < alpha.size(); i++) {
            alpha[i] = px[i * 4 + 3];
            if (alpha[i] == 255) rgb = (uint32_t)px[i * 4] << 16 | (uint32_t)px[i * 4 + 1] << 8 | px[i * 4 + 2];
        }
        stbi_image_free(px);
    }
    SDL_Texture *at(SDL_Renderer *ren, int height)
    {
        if (!sw || height <= 0) return nullptr;
        if (height > sh) height = sh;
        if (tex && height == h) return tex;
        if (tex) SDL_DestroyTexture(tex);
        tex = nullptr;
        h = height;
        w = (int)std::lround((double)sw * h / sh);
        std::vector<uint32_t> out((size_t)w * (size_t)h);
        for (int y = 0; y < h; y++) {
            const int y0 = y * sh / h, y1 = (y + 1) * sh / h > y0 ? (y + 1) * sh / h : y0 + 1;
            for (int x = 0; x < w; x++) {
                const int x0 = x * sw / w, x1 = (x + 1) * sw / w > x0 ? (x + 1) * sw / w : x0 + 1;
                unsigned sum = 0;
                for (int sy = y0; sy < y1; sy++)
                    for (int sx = x0; sx < x1; sx++) sum += alpha[(size_t)sy * sw + sx];
                const unsigned a = sum / (unsigned)((y1 - y0) * (x1 - x0));
                out[(size_t)y * w + x] = a << 24 | rgb;
            }
        }
        tex = SDL_CreateTexture(ren, SDL_PIXELFORMAT_ARGB8888, SDL_TEXTUREACCESS_STATIC, w, h);
        if (!tex) return nullptr;
        SDL_SetTextureBlendMode(tex, SDL_BLENDMODE_BLEND);
        SDL_SetTextureScaleMode(tex, SDL_ScaleModeLinear);
        SDL_UpdateTexture(tex, nullptr, out.data(), w * 4);
        return tex;
    }
    void release()
    {
        if (tex) SDL_DestroyTexture(tex);
        tex = nullptr;
    }
};

