extern "C" bool app_menu_run(SDL_Window *win)
{
    SDL_Renderer *ren = SDL_GetRenderer(win);
    if (!ren) return false;
    int lw = 0, lh = 0;
    SDL_RenderGetLogicalSize(ren, &lw, &lh);
    SDL_Texture *target = SDL_GetRenderTarget(ren);
    SDL_SetRenderTarget(ren, nullptr);
    Imgui ui;
    if (!ui.begin(win, ren)) {
        SDL_SetRenderTarget(ren, target);
        return false;
    }
    Logo logo;
    logo.load();
    int pic_w = 0, pic_h = 0;
    bool pic_exact = false;
    SDL_Texture *pic = nullptr;
    auto update_picture = [&](int out_w, int out_h) {
        int w = 0, h = 0;
        const uint32_t *picture = app_ui_picture(out_w, out_h, &w, &h, &pic_exact);
        if (!picture) return;
        if (!pic || w != pic_w || h != pic_h) {
            if (pic) SDL_DestroyTexture(pic);
            pic = SDL_CreateTexture(ren, SDL_PIXELFORMAT_ARGB8888, SDL_TEXTUREACCESS_STATIC, w, h);
            if (!pic) return;
            SDL_SetTextureScaleMode(pic, SDL_ScaleModeNearest);
            pic_w = w;
            pic_h = h;
        }
        SDL_UpdateTexture(pic, nullptr, picture, w * 4);
    };
    std::printf("[ducktales] menu open\n");
    std::fflush(stdout);
    Menu m;
    Uint64 last = SDL_GetTicks64();
    struct Step { int tab, category, capture, popup, w, h; bool focus; const char *name; };
    static const Step SCRIPT[] = {
        { TAB_SETTINGS, 0, -1, 0, 0, 0, false, "menu_01_settings_general" },
        { TAB_SETTINGS, 1, -1, 0, 0, 0, true, "menu_02_settings_graphics" },
        { TAB_SETTINGS, 2, -1, 0, 0, 0, false, "menu_03_settings_audio" },
        { TAB_SETTINGS, 3, -1, 0, 0, 0, false, "menu_04_settings_controls" },
        { TAB_SETTINGS, 3, 0, 0, 0, 0, false, "menu_05_settings_controls_capture" },
        { TAB_SETTINGS, 4, -1, 0, 0, 0, false, "menu_06_settings_gameplay" },
        { TAB_ENHANCEMENTS, 0, -1, 0, 0, 0, false, "menu_07_enhancements_gameplay" },
        { TAB_ENHANCEMENTS, 1, -1, 0, 0, 0, false, "menu_08_enhancements_restore_defaults" },
        { TAB_ABOUT, 0, -1, 0, 0, 0, false, "menu_09_about" },
        { TAB_SETTINGS, 1, -1, 0, 1280, 720, false, "menu_10_settings_graphics_720p" },
        { TAB_SETTINGS, 1, -1, 0, 3840, 2160, false, "menu_11_settings_graphics_2160p" },
        { TAB_ABOUT, 0, -1, 0, 3840, 2160, false, "menu_12_about_2160p" },
        { TAB_SETTINGS, 0, -1, 1, 0, 0, false, "menu_13_reset" },
        { TAB_SETTINGS, 0, -1, 2, 0, 0, false, "menu_14_quit" },
    };
    const bool selftest = selftest_dir() != nullptr;
    size_t step = 0;
    int step_frames = 0;
    SDL_Texture *offscreen = nullptr;
    int off_w = 0, off_h = 0;
    auto apply_step = [&](const Step &s) {
        m.tab = s.tab;
        m.category[s.tab] = s.category;
        m.capture_row = s.capture;
        m.capture_pad = false;
        m.ask_reset = s.popup == 1;
        m.ask_quit = s.popup == 2;
        m.focus_page = s.focus;
    };
    if (selftest) apply_step(SCRIPT[0]);
    while (!m.resume && !m.quit) {
        SDL_Event ev;
        while (SDL_PollEvent(&ev)) {
            if (menu_event(m, ev)) continue;
            ImGui_ImplSDL2_ProcessEvent(&ev);
        }
        if (m.resume || m.quit) break;
        AppMenuPrefs prefs;
        app_menu_prefs_get(&prefs);
        ImGuiIO &io = ImGui::GetIO();
        if (prefs.pad_nav) io.ConfigFlags |= ImGuiConfigFlags_NavEnableGamepad;
        else io.ConfigFlags &= ~ImGuiConfigFlags_NavEnableGamepad;
        SDL_RenderSetLogicalSize(ren, 0, 0);
        SDL_RenderSetViewport(ren, nullptr);
        int ow = 0, oh = 0;
        SDL_GetRendererOutputSize(ren, &ow, &oh);
        bool off = false;
        if (selftest && SCRIPT[step].w > 0) {
            if (!offscreen || off_w != SCRIPT[step].w || off_h != SCRIPT[step].h) {
                if (offscreen) SDL_DestroyTexture(offscreen);
                off_w = SCRIPT[step].w;
                off_h = SCRIPT[step].h;
                offscreen = SDL_CreateTexture(ren, SDL_PIXELFORMAT_ARGB8888, SDL_TEXTUREACCESS_TARGET, off_w, off_h);
            }
            off = offscreen && SDL_SetRenderTarget(ren, offscreen) == 0;
            if (off) {
                ow = off_w;
                oh = off_h;
            }
        }
        ui.fit(ui_base(win, oh));
        SDL_SetRenderDrawColor(ren, 0, 0, 0, 255);
        SDL_RenderClear(ren);
        update_picture(ow, oh);
        draw_picture(ren, pic, pic_w, pic_h, pic_exact, ow, oh);

        ImGui_ImplSDLRenderer2_NewFrame();
        ImGui_ImplSDL2_NewFrame();
        if (off) {
            io.DisplaySize = ImVec2((float)ow, (float)oh);
            io.DisplayFramebufferScale = ImVec2(1.0f, 1.0f);
        }
        ImGui::NewFrame();
        if (m.hold && !ImGui::IsKeyDown(ImGuiKey_GamepadFaceDown) && !ImGui::IsKeyDown(ImGuiKey_Enter) &&
            !ImGui::IsKeyDown(ImGuiKey_KeypadEnter) && !ImGui::IsKeyDown(ImGuiKey_Space))
            m.hold = false;
        draw_menu(m, ui.fonts, win, ren, logo);
        m.busy = ImGui::IsPopupOpen("", ImGuiPopupFlags_AnyPopupId | ImGuiPopupFlags_AnyPopupLevel) || ImGui::IsAnyItemActive();
        ImGui::Render();
        ImGui_ImplSDLRenderer2_RenderDrawData(ImGui::GetDrawData(), ren);
        if (selftest && ++step_frames == 6) {
            selftest_shot(ren, ow, oh, SCRIPT[step].name);
            step_frames = 0;
            if (++step == sizeof SCRIPT / sizeof SCRIPT[0]) m.resume = true;
            else apply_step(SCRIPT[step]);
        }
        if (off) SDL_SetRenderTarget(ren, nullptr);
        SDL_RenderPresent(ren);
        Uint64 now = SDL_GetTicks64();
        if (now - last < 16) SDL_Delay((Uint32)(16 - (now - last)));
        last = SDL_GetTicks64();
    }
    if (offscreen) SDL_DestroyTexture(offscreen);
    if (pic) SDL_DestroyTexture(pic);
    logo.release();
    ui.end();
    SDL_SetRenderTarget(ren, target);
    SDL_RenderSetLogicalSize(ren, lw, lh);
    SDL_SetRenderDrawBlendMode(ren, SDL_BLENDMODE_NONE);
    for (SDL_Event &ev : m.for_host) SDL_PushEvent(&ev);
    if (m.quit) {
        SDL_Event q;
        std::memset(&q, 0, sizeof q);
        q.type = SDL_QUIT;
        SDL_PushEvent(&q);
    }
    std::printf("[ducktales] menu closed%s\n", m.quit ? " (quit)" : "");
    std::fflush(stdout);
    return true;
}

