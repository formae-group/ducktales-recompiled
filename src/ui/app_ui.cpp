struct Fonts {
    ImFont *body = nullptr, *strong = nullptr, *small = nullptr, *title = nullptr;
    float base = 0.0f;
    bool system = false;   // a system UI font: the minus sign, the multiplication sign and the ellipsis exist
};

Fonts load_fonts(float base)
{
    Fonts f;
    f.base = base;
    ImGuiIO &io = ImGui::GetIO();
    io.Fonts->Clear();
    static ImVector<ImWchar> ranges;
    if (ranges.empty()) {
        ImFontGlyphRangesBuilder b;
        b.AddRanges(io.Fonts->GetGlyphRangesDefault());
        static const ImWchar extra[] = { 0x2013, 0x2014, 0x2026, 0x2026, 0x2212, 0x2212, 0x00D7, 0x00D7, 0 };
        b.AddRanges(extra);
        b.BuildRanges(&ranges);
    }
    std::string regular, semibold;
#ifdef _WIN32
    const char *windir = std::getenv("WINDIR");
    std::string dir = std::string(windir ? windir : "C:\\Windows") + "\\Fonts\\";
    regular = dir + "segoeui.ttf";
    semibold = dir + "seguisb.ttf";
#elif defined(__APPLE__)
    regular = semibold = "/System/Library/Fonts/SFNS.ttf";
#else
    regular = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf";
    semibold = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf";
#endif
    auto exists = [](const std::string &p) { FILE *t = std::fopen(p.c_str(), "rb"); if (t) std::fclose(t); return t != nullptr; };
    ImFontConfig cfg;
    cfg.OversampleH = 2;
    cfg.PixelSnapH = true;
    if (exists(regular)) {
        const char *heavy = exists(semibold) ? semibold.c_str() : regular.c_str();
        f.body = io.Fonts->AddFontFromFileTTF(regular.c_str(), base, &cfg, ranges.Data);
        f.strong = io.Fonts->AddFontFromFileTTF(heavy, base, &cfg, ranges.Data);
        f.small = io.Fonts->AddFontFromFileTTF(regular.c_str(), std::floor(base * 0.82f), &cfg, ranges.Data);
        f.title = io.Fonts->AddFontFromFileTTF(heavy, std::floor(base * 1.9f), &cfg, ranges.Data);
        f.system = f.body && f.strong && f.small && f.title;
    }
    if (!f.system) {
        io.Fonts->Clear();
        ImFontConfig d;
        d.SizePixels = std::floor(base);
        f.body = f.strong = io.Fonts->AddFontDefault(&d);
        d.SizePixels = std::floor(base * 0.82f);
        f.small = io.Fonts->AddFontDefault(&d);
        d.SizePixels = std::floor(base * 1.9f);
        f.title = io.Fonts->AddFontDefault(&d);
    }
    io.FontDefault = f.body;
    return f;
}

// The size everything is measured in: a 42nd of the drawable's height, at
// least 15 pixels at 96 DPI (scaled by the display's), at most a 20th.
float ui_base(SDL_Window *win, int out_h)
{
    float dpi = 96.0f, ddpi = 0.0f;
    int display = SDL_GetWindowDisplayIndex(win);
    if (display >= 0 && SDL_GetDisplayDPI(display, &ddpi, nullptr, nullptr) == 0 && ddpi > 0.0f) dpi = ddpi;
    float b = out_h / 42.0f;
    if (b < 15.0f * dpi / 96.0f) b = 15.0f * dpi / 96.0f;
    if (b > out_h / 20.0f) b = out_h / 20.0f;
    return std::floor(b < 10.0f ? 10.0f : b);
}

