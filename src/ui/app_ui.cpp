void draw_menu(Menu &m, const Fonts &F, SDL_Window *win, SDL_Renderer *ren, Logo &logo)
{
    const ImVec2 ds = ImGui::GetIO().DisplaySize;
    const float b = F.base;
    const float margin = std::floor(b * 1.1f), gap = std::floor(b * 0.5f), bar_h = std::floor(b * 2.0f);
    const float line = std::floor(b * 0.12f) < 1.0f ? 1.0f : std::floor(b * 0.12f);
    AppMenuPrefs prefs;
    app_menu_prefs_get(&prefs);
    ImGui::GetBackgroundDrawList()->AddRectFilled(ImVec2(0, 0), ds, (BACKDROP & ~IM_COL32_A_MASK) |
                                                  (ImU32)(prefs.opacity * 255 / 100) << IM_COL32_A_SHIFT);
    ImGui::SetNextWindowPos(ImVec2(0, 0));
    ImGui::SetNextWindowSize(ds);
    ImGui::PushStyleVar(ImGuiStyleVar_WindowPadding, ImVec2(0, 0));
    ImGui::Begin("##menu", nullptr, ImGuiWindowFlags_NoDecoration | ImGuiWindowFlags_NoMove | ImGuiWindowFlags_NoSavedSettings |
                 ImGuiWindowFlags_NoBackground | ImGuiWindowFlags_NoScrollWithMouse | ImGuiWindowFlags_NoBringToFrontOnFocus);
    ImGui::PopStyleVar();
    ImDrawList *dl = ImGui::GetWindowDrawList();
    const bool frozen = m.capture_row >= 0 || m.hold;
    if (frozen) {
        ImGui::PushStyleVar(ImGuiStyleVar_DisabledAlpha, 1.0f);
        ImGui::BeginDisabled();
    }

    ImGui::SetCursorScreenPos(ImVec2(margin, margin));
    ImGui::PushFont(F.strong);
    for (int t = 0; t < TAB_COUNT; t++) {
        if (t) ImGui::SameLine(0, std::floor(b * 0.25f));
        const float w = ImGui::CalcTextSize(TABS[t].name).x + std::floor(b * 1.6f);
        if (pick_button(TABS[t].name, m.tab == t, ImVec2(w, bar_h))) m.tab = t;
    }
    ImGui::PopFont();
    ImGui::SetCursorScreenPos(ImVec2(ds.x - margin - bar_h * 3.0f - gap * 2.0f, margin));
    if (icon_button("##reset", ICON_RESET, bar_h, false)) m.ask_reset = true;
    ImGui::SameLine(0, gap);
    if (icon_button("##quit", ICON_QUIT, bar_h, true)) m.ask_quit = true;
    ImGui::SameLine(0, gap);
    if (icon_button("##resume", ICON_RESUME, bar_h, false)) m.resume = true;
    const float rule_y = margin + bar_h + gap;
    dl->AddRectFilled(ImVec2(margin, rule_y), ImVec2(ds.x - margin, rule_y + line), ACCENT);

    const float top = rule_y + line + gap * 1.5f, body_h = ds.y - top - margin;
    const auto &tab = TABS[m.tab];
    int &chosen = m.category[m.tab];
    if (chosen < 0 || chosen >= tab.count) chosen = 0;
    ImGui::SetCursorScreenPos(ImVec2(margin, top));
    float page_x = margin, page_w = ds.x - 2.0f * margin;
    if (tab.count) {
        const float side_w = std::floor(b * 10.0f);
        ImGui::BeginChild("##categories", ImVec2(side_w, body_h), ImGuiChildFlags_NavFlattened);
        for (int c = 0; c < tab.count; c++)
            if (pick_button(tab.categories[c].name, chosen == c, ImVec2(side_w, std::floor(b * 1.9f)))) chosen = c;
        ImGui::EndChild();
        const float sep_x = margin + side_w + gap;
        dl->AddRectFilled(ImVec2(sep_x, top), ImVec2(sep_x + line, top + body_h), LINE);
        page_x = sep_x + line + gap;
        page_w = ds.x - margin - page_x;
        if (page_w > b * 36.0f) page_w = std::floor(b * 36.0f);
    } else if (page_w > b * 60.0f) {
        page_w = std::floor(b * 60.0f);
    }
    ImGui::SetCursorScreenPos(ImVec2(page_x, top));
    ImGui::PushID(m.tab * 16 + chosen);
    ImGui::BeginChild("##page", ImVec2(page_w, body_h), ImGuiChildFlags_NavFlattened | ImGuiChildFlags_AlwaysUseWindowPadding);
    if (m.focus_page) {
        ImGui::SetKeyboardFocusHere();
        ImGui::SetNavCursorVisible(true);
        m.focus_page = false;
    }
    if (tab.count) {
        Page p{ m, F, win };
        tab.categories[chosen].draw(p);
    } else {
        page_about(F, logo, ren);
    }
    ImGui::EndChild();
    ImGui::PopID();

    if (frozen) {
        ImGui::EndDisabled();
        ImGui::PopStyleVar();
    }
    if (confirm(F, "##reset-confirm", &m.ask_reset, "Reset the game?", "Reset")) {
        dt_soft_reset();
        m.resume = true;
    }
    if (confirm(F, "##quit-confirm", &m.ask_quit, "Quit DuckTales?", "Quit")) m.quit = true;
    ImGui::End();
}

