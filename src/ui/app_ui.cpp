void section(const char *title)
{
    ImGui::PushStyleColor(ImGuiCol_Text, TEXT_DIM);
    ImGui::SeparatorText(title);
    ImGui::PopStyleColor();
}

void tag(const char *text)
{
    if (!text) return;
    ImGui::SameLine();
    ImGui::PushStyleColor(ImGuiCol_Text, ACCENT);
    ImGui::TextUnformatted(text);
    ImGui::PopStyleColor();
}

// A label on the left and a combo on the right half.
bool choice(const char *label, int *v, const char *const *names, int count, const char *note = nullptr)
{
    bool changed = false;
    ImGui::PushID(label);
    const float x0 = ImGui::GetCursorPosX(), full = ImGui::GetContentRegionAvail().x, w = std::floor(full * 0.5f);
    ImGui::AlignTextToFramePadding();
    ImGui::TextUnformatted(label);
    tag(note);
    ImGui::SameLine(x0 + full - w);
    ImGui::SetNextItemWidth(w);
    const int cur = *v < 0 || *v >= count ? 0 : *v;
    if (ImGui::BeginCombo("##choice", names[cur])) {
        for (int i = 0; i < count; i++) {
            const bool selected = i == cur;
            if (ImGui::Selectable(names[i], selected) && !selected) {
                *v = i;
                changed = true;
            }
            if (selected) ImGui::SetItemDefaultFocus();
        }
        ImGui::EndCombo();
    }
    ImGui::PopID();
    return changed;
}

// A label above a slider with - and + buttons on either side.
bool stepper(const Fonts &F, const char *label, int *v, int lo, int hi, int step, const char *format, const char *note = nullptr)
{
    const int was = *v;
    ImGui::PushID(label);
    ImGui::TextUnformatted(label);
    tag(note);
    const ImGuiStyle &s = ImGui::GetStyle();
    const float b = ImGui::GetFrameHeight(), w = ImGui::GetContentRegionAvail().x;
    ImGui::PushItemFlag(ImGuiItemFlags_ButtonRepeat, true);
    if (ImGui::Button(F.system ? "\xE2\x88\x92##dec" : "-##dec", ImVec2(b, b))) *v -= step;
    ImGui::SameLine(0, s.ItemInnerSpacing.x);
    ImGui::SetNextItemWidth(w - 2.0f * (b + s.ItemInnerSpacing.x));
    ImGui::SliderInt("##value", v, lo, hi, format, ImGuiSliderFlags_AlwaysClamp | ImGuiSliderFlags_NoInput);
    ImGui::SameLine(0, s.ItemInnerSpacing.x);
    if (ImGui::Button("+##inc", ImVec2(b, b))) *v += step;
    ImGui::PopItemFlag();
    ImGui::PopID();
    if (*v < lo) *v = lo;
    if (*v > hi) *v = hi;
    return *v != was;
}

// A tab or a category: filled with the accent while chosen. With a keyboard
// or a controller, moving onto one chooses it (only a move: the focus that
// falls back onto one when the page under it changes does not).
bool pick_button(const char *label, bool chosen, ImVec2 size)
{
    ImGui::PushStyleColor(ImGuiCol_Button, chosen ? ACCENT : CLEAR);
    ImGui::PushStyleColor(ImGuiCol_ButtonHovered, chosen ? ACCENT_HI : SOFT_HOVER);
    ImGui::PushStyleColor(ImGuiCol_ButtonActive, chosen ? ACCENT_HI : SOFT_ACTIVE);
    ImGui::PushStyleColor(ImGuiCol_Text, chosen ? ON_ACCENT : TEXT);
    const bool pressed = ImGui::Button(label, size);
    ImGui::PopStyleColor(4);
    return pressed || (!chosen && ImGui::GetCurrentContext()->NavJustMovedToId == ImGui::GetItemID());
}

enum Icon { ICON_RESET, ICON_QUIT, ICON_RESUME };

bool icon_button(const char *id, Icon icon, float size, bool danger)
{
    if (danger) {
        ImGui::PushStyleColor(ImGuiCol_Button, DANGER);
        ImGui::PushStyleColor(ImGuiCol_ButtonHovered, DANGER_HI);
        ImGui::PushStyleColor(ImGuiCol_ButtonActive, DANGER_HI);
    }
    const bool pressed = ImGui::Button(id, ImVec2(size, size));
    if (danger) ImGui::PopStyleColor(3);
    const ImVec2 a = ImGui::GetItemRectMin(), q = ImGui::GetItemRectMax();
    const ImVec2 c((a.x + q.x) * 0.5f, (a.y + q.y) * 0.5f);
    const float r = size * 0.24f, t = size * 0.075f < 1.5f ? 1.5f : size * 0.075f;
    const ImU32 col = ImGui::GetColorU32(ImGuiCol_Text);
    ImDrawList *dl = ImGui::GetWindowDrawList();
    switch (icon) {
    case ICON_QUIT:
        dl->PathArcTo(c, r, -PI * 0.5f + 0.75f, PI * 1.5f - 0.75f, 28);
        dl->PathStroke(col, 0, t);
        dl->AddLine(ImVec2(c.x, c.y - r * 1.3f), ImVec2(c.x, c.y - r * 0.2f), col, t);
        break;
    case ICON_RESET: {
        const float a0 = -PI * 0.5f, a1 = a0 + PI * 1.5f;
        dl->PathArcTo(c, r, a0, a1, 28);
        dl->PathStroke(col, 0, t);
        const ImVec2 n(std::cos(a1), std::sin(a1)), d(-n.y, n.x), p(c.x + n.x * r, c.y + n.y * r);
        const float h = r * 0.62f;
        dl->AddTriangleFilled(ImVec2(p.x + d.x * h, p.y + d.y * h), ImVec2(p.x + n.x * h - d.x * h * 0.25f, p.y + n.y * h - d.y * h * 0.25f),
                              ImVec2(p.x - n.x * h - d.x * h * 0.25f, p.y - n.y * h - d.y * h * 0.25f), col);
        break;
    }
    case ICON_RESUME:
        dl->AddTriangleFilled(ImVec2(c.x - r * 0.7f, c.y - r * 0.95f), ImVec2(c.x - r * 0.7f, c.y + r * 0.95f),
                              ImVec2(c.x + r * 0.95f, c.y), col);
        break;
    }
    return pressed;
}

// A centred question with a button that confirms and Cancel (Esc / B).
bool confirm(const Fonts &F, const char *id, bool *ask, const char *question, const char *yes)
{
    if (*ask) {
        ImGui::OpenPopup(id);
        *ask = false;
    }
    const ImVec2 ds = ImGui::GetIO().DisplaySize;
    ImGui::SetNextWindowPos(ImVec2(ds.x * 0.5f, ds.y * 0.5f), ImGuiCond_Always, ImVec2(0.5f, 0.5f));
    if (!ImGui::BeginPopupModal(id, nullptr, ImGuiWindowFlags_NoDecoration | ImGuiWindowFlags_AlwaysAutoResize |
                                                 ImGuiWindowFlags_NoSavedSettings | ImGuiWindowFlags_NoMove))
        return false;
    bool confirmed = false;
    ImGui::PushFont(F.strong);
    ImGui::TextUnformatted(question);
    ImGui::PopFont();
    ImGui::Dummy(ImVec2(0, std::floor(F.base * 0.4f)));
    const float w = std::floor(F.base * 7.0f);
    if (ImGui::Button(yes, ImVec2(w, 0))) {
        confirmed = true;
        ImGui::CloseCurrentPopup();
    }
    ImGui::SetItemDefaultFocus();
    ImGui::SameLine();
    if (ImGui::Button("Cancel", ImVec2(w, 0)) || ImGui::IsKeyPressed(ImGuiKey_Escape, false) ||
        ImGui::IsKeyPressed(ImGuiKey_GamepadFaceRight, false))
        ImGui::CloseCurrentPopup();
    ImGui::EndPopup();
    return confirmed;
}

