extern "C" int app_ui_first_run(const char *expected, char *rom_out, size_t cap)
{
    if (SDL_Init(SDL_INIT_VIDEO | SDL_INIT_GAMECONTROLLER) != 0) return 2;
    const bool selftest = selftest_dir() != nullptr;
    SDL_Window *win = SDL_CreateWindow("DuckTales", SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED, 960, 640,
                                       SDL_WINDOW_RESIZABLE | SDL_WINDOW_ALLOW_HIGHDPI | (selftest ? SDL_WINDOW_HIDDEN : 0));
    int selftest_frames = 0;
    SDL_Renderer *ren = win ? SDL_CreateRenderer(win, -1, SDL_RENDERER_ACCELERATED | SDL_RENDERER_PRESENTVSYNC) : nullptr;
    if (win && !ren) ren = SDL_CreateRenderer(win, -1, 0);
    Imgui ui;
    if (!ren || !ui.begin(win, ren)) {
        if (ren) SDL_DestroyRenderer(ren);
        if (win) SDL_DestroyWindow(win);
        SDL_Quit();
        return 2;
    }
    char data_dir[1024] = "";
    app_data_dir(data_dir, sizeof data_dir);
    std::string error, detail;
    int result = -1;
    bool first_frame = true;
    Uint64 done_at = 0;
    std::string chosen;
    while (result < 0) {
        SDL_Event ev;
        while (SDL_PollEvent(&ev)) {
            if (ev.type == SDL_QUIT) result = 1;
            if (ev.type == SDL_DROPFILE) {
                chosen = ev.drop.file;
                SDL_free(ev.drop.file);
                continue;
            }
            ImGui_ImplSDL2_ProcessEvent(&ev);
        }
        if (!chosen.empty() && !done_at) {
            char actual[65] = "";
            AppRomStatus s = app_rom_import(chosen.c_str(), expected, rom_out, cap, actual);
            if (s == APP_ROM_OK) {
                error.clear();
                done_at = SDL_GetTicks64();
            } else {
                error = app_rom_status_text(s);
                detail = s == APP_ROM_MISMATCH ? std::string("SHA-256 of this file: ") + actual + "\nExpected: " + expected : std::string();
            }
            std::fprintf(stderr, "[ducktales] %s: %s\n", chosen.c_str(), app_rom_status_text(s));
            chosen.clear();
        }
        if (done_at && SDL_GetTicks64() - done_at > 900) result = 0;

        int ow = 0, oh = 0;
        SDL_GetRendererOutputSize(ren, &ow, &oh);
        ui.fit(ui_base(win, oh));
        ImGui_ImplSDLRenderer2_NewFrame();
        ImGui_ImplSDL2_NewFrame();
        ImGui::NewFrame();
        const Fonts &F = ui.fonts;
        const float b = F.base;
        const ImVec2 ds = ImGui::GetIO().DisplaySize;
        const float margin = std::floor(b * 1.1f), gap = std::floor(b * 0.5f), bar_h = std::floor(b * 2.0f);
        const float line = std::floor(b * 0.12f) < 1.0f ? 1.0f : std::floor(b * 0.12f);
        ImGui::GetBackgroundDrawList()->AddRectFilled(ImVec2(0, 0), ds, BACKDROP);
        ImGui::SetNextWindowPos(ImVec2(0, 0));
        ImGui::SetNextWindowSize(ds);
        ImGui::PushStyleVar(ImGuiStyleVar_WindowPadding, ImVec2(0, 0));
        ImGui::Begin("##first-run", nullptr, ImGuiWindowFlags_NoDecoration | ImGuiWindowFlags_NoMove |
                     ImGuiWindowFlags_NoSavedSettings | ImGuiWindowFlags_NoBackground);
        ImGui::PopStyleVar();
        ImDrawList *dl = ImGui::GetWindowDrawList();
        dl->AddText(F.strong, F.strong->FontSize, ImVec2(margin, margin + std::floor((bar_h - F.strong->FontSize) * 0.5f)), TEXT,
                    "DuckTales Recompiled");
        dl->AddRectFilled(ImVec2(margin, margin + bar_h + gap), ImVec2(ds.x - margin, margin + bar_h + gap + line), ACCENT);

        float col_w = ds.x - margin * 2.0f;
        if (col_w > b * 30.0f) col_w = std::floor(b * 30.0f);
        const float x = std::floor((ds.x - col_w) * 0.5f);
        ImGui::SetCursorScreenPos(ImVec2(x, std::floor(margin + bar_h + gap + (ds.y - margin - bar_h) * 0.14f)));
        ImGui::PushTextWrapPos(x + col_w);
        ImGui::PushFont(F.title);
        ImGui::TextUnformatted("Choose your ROM");
        ImGui::PopFont();
        ImGui::SetCursorPosX(x);
        ImGui::PushStyleColor(ImGuiCol_Text, TEXT_DIM);
        ImGui::TextWrapped("This port runs on your own copy of the game. Choose your DuckTales (USA) cartridge image "
                           "(.nes), or drop it onto this window. It is checked against the original, then kept in "
                           "your user folder, so the game starts directly next time.");
        ImGui::PopStyleColor();
        ImGui::Dummy(ImVec2(0, b));
        ImGui::SetCursorPosX(x);
        const bool busy = done_at != 0;
        ImGui::BeginDisabled(busy);
        const float button_h = std::floor(b * 2.2f);
        ImGui::PushFont(F.strong);
        ImGui::PushStyleColor(ImGuiCol_Button, ACCENT);
        ImGui::PushStyleColor(ImGuiCol_ButtonHovered, ACCENT_HI);
        ImGui::PushStyleColor(ImGuiCol_ButtonActive, ACCENT_HI);
        ImGui::PushStyleColor(ImGuiCol_Text, ON_ACCENT);
        if (ImGui::Button(F.system ? "Choose ROM file\xE2\x80\xA6" : "Choose ROM file...", ImVec2(std::floor(b * 11.0f), button_h)))
            chosen = pick_file(win);
        ImGui::PopStyleColor(4);
        ImGui::SetItemDefaultFocus();
        ImGui::SameLine(0, gap);
        if (ImGui::Button("Quit", ImVec2(std::floor(b * 6.0f), button_h))) result = 1;
        ImGui::PopFont();
        ImGui::EndDisabled();
        if (first_frame) ImGui::SetNavCursorVisible(true);
        first_frame = false;
        if (ImGui::IsKeyPressed(ImGuiKey_Escape, false) || ImGui::IsKeyPressed(ImGuiKey_GamepadFaceRight, false)) result = 1;
        ImGui::Dummy(ImVec2(0, gap));
        ImGui::SetCursorPosX(x);
        if (busy) {
            ImGui::PushStyleColor(ImGuiCol_Text, OK_TEXT);
            ImGui::TextUnformatted("Verified. Starting the game.");
            ImGui::PopStyleColor();
        } else if (!error.empty()) {
            ImGui::PushStyleColor(ImGuiCol_Text, ERROR_TEXT);
            ImGui::TextWrapped("%s", error.c_str());
            ImGui::PopStyleColor();
            if (!detail.empty()) {
                ImGui::SetCursorPosX(x);
                ImGui::PushFont(F.small);
                ImGui::PushStyleColor(ImGuiCol_Text, TEXT_DIM);
                ImGui::TextWrapped("%s", detail.c_str());
                ImGui::PopStyleColor();
                ImGui::PopFont();
            }
        }
        ImGui::PopTextWrapPos();
        std::string where = std::string("Your copy is stored in ") + (data_dir[0] ? data_dir : "your user data folder") + ".";
        dl->AddText(F.small, F.small->FontSize, ImVec2(x, ds.y - margin - F.small->FontSize * 2.4f), TEXT_OFF, where.c_str(),
                    nullptr, col_w);
        ImGui::End();
        ImGui::Render();
        SDL_SetRenderDrawColor(ren, 0, 0, 0, 255);
        SDL_RenderClear(ren);
        ImGui_ImplSDLRenderer2_RenderDrawData(ImGui::GetDrawData(), ren);
        if (selftest) {
            ++selftest_frames;
            if (selftest_frames == 6) {
                selftest_shot(ren, ow, oh, "first_run_1_welcome");
                const char *pick = std::getenv("DUCKTALES_UI_SELFTEST_PICK");
                if (pick && *pick) chosen = pick;
                else result = 1;
            }
            if (selftest_frames == 12) {
                selftest_shot(ren, ow, oh, "first_run_2_result");
                if (!done_at) result = 1;
            }
        }
        SDL_RenderPresent(ren);
        SDL_Delay(1);
    }
    ui.end();
    SDL_DestroyRenderer(ren);
    SDL_DestroyWindow(win);
    SDL_Quit();
    return result;
}
