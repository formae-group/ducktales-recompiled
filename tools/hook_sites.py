"""The game.toml [[mod_function_hook]] sites as C, for the build with no ROM (docs/ROMLESS.md).

The ROM build takes cyc_native_hook_sites from the code NESRecomp generates; the
build with no ROM (DUCKTALES_ROMLESS) has none, and CMake writes the same table
from config/game.toml with this script: id, address, and the content key (length
and CRC-32 of the bytes there), which the native runtime checks against the
imported ROM before a site fires (src/native/native_hooks.c).

    py -3 -I tools/hook_sites.py config/game.toml build/romless/hook_sites.c

The file is rewritten only when its text changes.
"""

import sys
import tomllib
from pathlib import Path


def main():
    if len(sys.argv) != 3:
        sys.exit('usage: hook_sites.py GAME_TOML OUT_C')
    game, out = Path(sys.argv[1]), Path(sys.argv[2])
    sites = tomllib.loads(game.read_text(encoding='utf-8')).get('mod_function_hook', [])
    if not sites:
        sys.exit(f'{game}: no [[mod_function_hook]] sites')
    rows = []
    for site in sites:
        name = f'"{site["id"]}"' if 'id' in site else 'NULL'
        rows.append(f'    {{ {name}, 0x{site["addr"]:04X}, {site.get("length", 0)}, 0x{site.get("crc32", 0):08X}u }},')
    text = '\n'.join(
        [
            f'/* Generated by tools/hook_sites.py from {game.name}. DO NOT EDIT. */',
            '#include "cyc_recomp.h"',
            '',
            f'const CycHookSite cyc_native_hook_sites[{len(sites)}] = {{',
            *rows,
            '};',
            f'const uint32_t cyc_native_hook_site_count = {len(sites)}u;',
            '',
        ]
    )
    if not out.exists() or out.read_text(encoding='utf-8') != text:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
