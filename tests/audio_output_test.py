"""Presented sound of the native player (docs/audio.md, "Output stage"), headless.

ducktales.exe (build/windows, the native player) runs each route off screen with
--audio-out: the window's frame loop and the audio device on simulated clocks
(--audio-sim, native_window.c), the sound going through the same output stage
(src/native/native_output.c) the window feeds the device with. The WAV it writes is
stereo: left what the device played, right half the game's own sample each output
sample was made from (the synth with the extra voices, after the queue's resampling and
before the mods' files, volume and limiter; halved so a sum over full scale fits), or
-32768 where the device played none. Steps the mods' files, the fades or the limiter
would make show against it; the replacement files are low sines (30 Hz music, 20 Hz
effects, both at full scale), whose own steps stay under the threshold.

Every run must show
  - no output sample at or beyond full scale (|s| >= 32767);
  - no discontinuity: a step |out[i] - out[i-1]| larger than the game's own largest step
    around it (|game[k] - game[k-1]|, k = i-1..i+1) plus 1% of full scale (328), counting
    the step from silence to the first sample and from the last one to silence (the
    device closing);
  - no underrun (the queue running dry while sound plays), except in the run that
    blocks the frame loop with no warning (hitch), where the one underrun must be
    declicked like the rest.
It reports the mix's peak (before the limiter) and the output's peak in dBFS, and the
queue's statistics.

Runs: every route at the defaults (No slowdown off, VSync at 144 Hz, volume 100) and in
the worst case (No slowdown on, both extra voices on, a mod replacing the music and
every effect with full-scale files, volume 100, VSync at 60 Hz, device clock +300 ppm);
on amazon_intro VSync at 60 and 120 Hz and none (a minimised window), the window events
(menu paused, fast-forward, a 1.5 s window drag, a loaded state, sound off, a volume
sweep 100-0-100, a 480-sample device buffer) at the defaults and in the worst case, and
a 120 ms hitch; on full_african_mines the device clock 500 ppm fast and slow.

    py -3 -I tests/audio_output_test.py --build build/windows [--routes R ...] [--jobs 2] [--keep]

Needs numpy. WAVs go to captures/audio_output and are deleted unless --keep is given.
"""

import argparse
import io
import math
import re
import struct
import subprocess
import sys
import wave
import zipfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from romfile import default_rom  # noqa: E402

RATE = 48000
TAU = 328
PRG_SHA256 = '8ba8baed01a9fbaf1e9ff29e0c9825db1963ac2aff211d6f1f3bcfd3839e2013'
EVENTS = 'menu=600:180,fast=1200:300,drag=1800:1500,load=2400,off=2700:120,sweep=3000,period=480'
STAT = re.compile(r'(\w+)=(-?[\d.]+)')


def route_frames(path):
    last = 0
    for line in path.read_text().splitlines():
        if line.strip() and not line.startswith('#'):
            last = max(last, int(line.split()[0]))
    return last + 120


def tone(freq, seconds):
    out = bytearray()
    for i in range(int(RATE * seconds)):
        out += struct.pack('<h', int(32767 * math.sin(2 * math.pi * freq * i / RATE)))
    buf = io.BytesIO()
    with wave.open(buf, 'wb') as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(bytes(out))
    return buf.getvalue()


def loud_mod(folder):
    """Every music id and every effect id replaced by a full-scale file."""
    folder.mkdir(parents=True, exist_ok=True)
    music, effect = tone(30, 2.0), tone(20, 0.4)
    toml = (
        'id = "loud"\nname = "Loud"\nversion = "1.0.0"\nauthor = "audio_output_test"\n'
        f'description = """Generated by tests/audio_output_test.py."""\ngame = "DuckTales (USA)"\n'
        f'prg_sha256 = "{PRG_SHA256}"\n'
    )
    with zipfile.ZipFile(folder / 'loud.dtmod', 'w', zipfile.ZIP_DEFLATED) as z:
        z.writestr('mod.toml', toml)
        for i in range(0x10):
            z.writestr(f'music/{i:02X}.wav', music)
        for i in range(0x10, 0x38):
            z.writestr(f'sfx/{i:02X}.wav', effect)


def run(job, args, exe, mods):
    name, route, worst, sim = job
    out = Path(args.out) / f'{name}.wav'
    cmd = [
        str(exe),
        args.rom,
        '--input',
        str(route),
        '--frames',
        str(route_frames(route)),
        '--lag',
        'none' if worst else 'faithful',
        '--config',
        str(Path(args.out) / 'x.ini'),
        '--music-under-effects',
        'on' if worst else 'off',
        '--overlap-effects',
        'on' if worst else 'off',
        '--audio-out',
        str(out),
        '--audio-sim',
        sim,
    ]
    if worst:
        cmd += ['--mods', 'on', '--mods-dir', str(mods)]
    p = subprocess.run(cmd, capture_output=True, text=True)
    if p.returncode:
        raise SystemExit(f'{name}: exit {p.returncode}\n{p.stdout}{p.stderr}')
    line = next((l for l in p.stdout.splitlines() if l.startswith('native player: audio:')), '')
    stats = {k: float(v) for k, v in STAT.findall(line)}
    with wave.open(str(out)) as w:
        a = np.frombuffer(w.readframes(w.getnframes()), '<i2').reshape(-1, 2).astype(np.int64)
    if not args.keep:
        out.unlink()
    y, g = a[:, 0], a[:, 1]
    full = int(np.sum((y >= 32767) | (y <= -32767)))
    valid = g != -32768
    dg = 2 * np.abs(np.diff(g)) + 2
    dg[~(valid[1:] & valid[:-1])] = 0
    bound = dg.copy()
    bound[1:] = np.maximum(bound[1:], dg[:-1])
    bound[:-1] = np.maximum(bound[:-1], dg[1:])
    excess = np.abs(np.diff(y)) - bound - TAU
    edges = [abs(int(y[0])) - TAU, abs(int(y[-1])) - TAU] if len(y) else [0, 0]
    clicks = int(np.sum(excess > 0)) + sum(e > 0 for e in edges)
    worst_excess = max([int(excess.max()) if len(excess) else 0, *edges]) + TAU
    peak = int(np.abs(y).max()) if len(y) else 0
    return name, stats, full, clicks, worst_excess, peak


def dbfs(v):
    return f'{20 * math.log10(v / 32768):+.2f}' if v > 0 else '-inf'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--build', default='build/windows')
    ap.add_argument('--config', default='Release')
    ap.add_argument('--rom', default=default_rom())
    ap.add_argument('--routes', nargs='*')
    ap.add_argument('--jobs', type=int, default=2)
    ap.add_argument('--out', default=str(ROOT / 'captures' / 'audio_output'))
    ap.add_argument('--keep', action='store_true')
    args = ap.parse_args()
    exe = ROOT / args.build / args.config / 'ducktales.exe'
    Path(args.out).mkdir(parents=True, exist_ok=True)
    mods = Path(args.out) / 'mods'
    loud_mod(mods)
    routes = sorted((ROOT / 'tests' / 'routes').glob('*.txt'))
    if args.routes:
        routes = [r for r in routes if r.stem in args.routes]
    by = {r.stem: r for r in sorted((ROOT / 'tests' / 'routes').glob('*.txt'))}
    worst_sim = 'refresh=60,drift=300'
    jobs = []
    for r in routes:
        jobs.append((f'{r.stem}.default', r, False, 'refresh=144'))
        jobs.append((f'{r.stem}.worst', r, True, worst_sim))
    if not args.routes:
        amazon, mines = by['amazon_intro'], by['full_african_mines']
        jobs += [
            ('amazon_intro.vsync60', amazon, False, 'refresh=60'),
            ('amazon_intro.vsync120', amazon, False, 'refresh=120'),
            ('amazon_intro.minimised', amazon, False, 'refresh=0'),
            ('amazon_intro.events', amazon, False, 'refresh=144,' + EVENTS),
            ('amazon_intro.events.worst', amazon, True, worst_sim + ',' + EVENTS),
            ('amazon_intro.hitch', amazon, False, 'refresh=144,hitch=1500:120'),
            ('full_african_mines.fast_clock', mines, False, 'refresh=144,drift=500'),
            ('full_african_mines.slow_clock', mines, False, 'refresh=144,drift=-500'),
        ]
    failures = []
    print(
        f'{"run":34s} {"mix peak":>9s} {"out peak":>9s} {"at FS":>6s} {"clicks":>6s} {"max step":>8s} '
        f'{"underruns":>9s} {"dropped":>7s} {"stretch":>7s} {"shrunk":>6s} {"limited":>8s} {"queue ms":>8s}'
    )
    with ThreadPoolExecutor(args.jobs) as ex:
        for name, st, full, clicks, step, peak in ex.map(lambda j: run(j, args, exe, mods), jobs):
            allowed = 1 if name.endswith('.hitch') else 0
            under = int(st.get('underruns', -1))
            ok = full == 0 and clicks == 0 and 0 <= under <= allowed
            mix_peak = st.get('peak_in', -999)
            print(
                f'{name:34s} {mix_peak:+9.2f} {dbfs(peak):>9s} {full:6d} {clicks:6d} {step:8d} {under:9d} '
                f'{int(st.get("dropped", 0)):7d} {int(st.get("stretched", 0)):7d} {int(st.get("shrunk", 0)):6d} '
                f'{int(st.get("limited", 0)):8d} {st.get("max_queue_ms", 0):8.1f}  {"ok" if ok else "FAIL"}',
                flush=True,
            )
            if not ok:
                failures.append(name)
    for f in mods.glob('*'):
        f.unlink()
    mods.rmdir()
    print(f'\n{"FAILED: " + ", ".join(failures) if failures else "all audio output checks passed"}')
    return 1 if failures else 0


if __name__ == '__main__':
    sys.exit(main())
